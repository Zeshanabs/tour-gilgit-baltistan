const seed = async () => {
  try {
    await connectDB();
    await Place.deleteMany({});
    await TourPackage.deleteMany({});

    const createdPlaces = await Place.insertMany(placesData);
    const placeMap = createdPlaces.reduce((map, place) => {
      map[place.slug] = place._id;
      return map;
    }, {});

    const toursWithPlaces = toursData.map((tour) => {
      const includedSlugs = [];

      if (tour.slug === 'hunza-valley-explorer') {
        includedSlugs.push('karimabad', 'baltit-fort', 'attabad-lake', 'passu-cones', 'khunjerab-pass');
      }
      if (tour.slug === 'skardu-deosai-adventure') {
        includedSlugs.push('skardu-city', 'shangrila-resort', 'deosai-national-park', 'satpara-lake');
      }
      if (tour.slug === 'fairy-meadows-nanga-parbat-trek') {
        includedSlugs.push('fairy-meadows', 'nanga-parbat-base-camp-view', 'chilas');
      }
      if (tour.slug === 'grand-gilgit-baltistan-tour') {
        includedSlugs.push('karimabad', 'baltit-fort', 'attabad-lake', 'skardu-city', 'deosai-national-park', 'fairy-meadows');
      }

      return {
        ...tour,
        includedPlaces: includedSlugs.map((slug) => placeMap[slug]).filter(Boolean),
      };
    });

    await TourPackage.insertMany(toursWithPlaces);

    console.log('Seed completed successfully.');
    process.exit(0);
  } catch (error) {
    console.error('Seed failed:', error);
    process.exit(1);
  }
};

